#ifndef USB_DLP_XP_FILTER_PROTOCOL_H
#define USB_DLP_XP_FILTER_PROTOCOL_H

#define USB_DLP_FILTER_PROTOCOL_VERSION 1
#define USB_DLP_FILTER_NAME_CAPACITY 256

#define IOCTL_USB_DLP_FILTER_SET_ALLOWED \
  CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_USB_DLP_FILTER_QUERY \
  CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_READ_DATA)

typedef struct _USB_DLP_FILTER_REQUEST {
  ULONG version;
  ULONG allowed;
  WCHAR physical_device_name[USB_DLP_FILTER_NAME_CAPACITY];
} USB_DLP_FILTER_REQUEST;

typedef struct _USB_DLP_FILTER_REPLY {
  ULONG version;
  ULONG found;
  ULONG allowed;
  ULONG attached_usb_disks;
} USB_DLP_FILTER_REPLY;

#endif
